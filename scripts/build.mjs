import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { discoverGames } from './discover.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outArg = process.argv.indexOf('--outdir');
const outdir = join(root, outArg > 1 && process.argv[outArg + 1] ? process.argv[outArg + 1] : 'dist');
const gamesDir = join(root, 'src', 'games');

mkdirSync(gamesDir, { recursive: true });
const ids = discoverGames(gamesDir);
const imports = ids.map((id, i) => `import game${i} from './${id}/index';`).join('\n');
const list = ids.map((_, i) => `game${i}`).join(', ');
const registry = `// GENERATED by scripts/build.mjs - do not edit.
import type { Game } from '../core/types';
${imports}

export const games: Game<any>[] = [${list}];
`;
writeFileSync(join(gamesDir, 'registry.generated.ts'), registry);

await build({
  entryPoints: ['arcade', 'signal', 'launch'].map((n) => join(root, 'src', `${n}.ts`)),
  outdir,
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'cjs',
});
console.log(`built (${ids.length} games: ${ids.join(', ') || 'none'})`);
